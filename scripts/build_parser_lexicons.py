#!/usr/bin/env python3
"""Regenerates the data-derived lexicons used by CharacterNameParserV2.

  given-names.tsv   SSA state-level baby-name counts (namesbystate_part*.zip in the repo
                    root), summed over states, years and sexes. Format: name<TAB>count.
  english-words.txt Common English words from SCOWL (http://wordlist.aspell.net/), size
                    levels 10-60, american + english, lowercase alphabetic words only.

Usage: scripts/build_parser_lexicons.py <path-to-scowl-final-dir>
The hand-curated lists in src/main/resources/parser/v2 are edited by hand, not generated.
"""
import collections, glob, io, os, re, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'main', 'resources', 'parser', 'v2')

def build_given_names():
    counts = collections.Counter()
    for z in sorted(glob.glob(os.path.join(ROOT, 'namesbystate_part*.zip'))):
        with zipfile.ZipFile(z) as zf:
            for member in zf.namelist():
                if not member.upper().endswith('.TXT'):
                    continue
                for line in io.TextIOWrapper(zf.open(member), encoding='latin-1'):
                    parts = line.strip().split(',')
                    if len(parts) == 5:
                        counts[parts[3].lower()] += int(parts[4])
    with open(os.path.join(OUT, 'given-names.tsv'), 'w', encoding='utf-8') as f:
        f.write('# Given-name lexicon derived from SSA state-level baby-name files (namesbystate_part*.zip).\n')
        f.write('# name<TAB>total births 1910-present, all states, both sexes. Generated by scripts/build_parser_lexicons.py\n')
        for name, c in sorted(counts.items()):
            f.write(f'{name}\t{c}\n')
    return len(counts)

def build_english_words(scowl_final):
    words = set()
    for level in (10, 20, 35, 40, 50, 55, 60):
        for variant in ('english', 'american'):
            path = os.path.join(scowl_final, f'{variant}-words.{level}')
            if not os.path.exists(path):
                continue
            for w in open(path, encoding='latin-1'):
                w = w.strip()
                if re.fullmatch(r'[a-z]{2,}', w):
                    words.add(w)
    with open(os.path.join(OUT, 'english-words.txt'), 'w', encoding='utf-8') as f:
        f.write('# Common English words (lowercase), from SCOWL size levels 10-60.\n')
        f.write('# SCOWL: Copyright 2000-2018 by Kevin Atkinson. Permission to use, copy, modify, distribute\n')
        f.write('# and sell these word lists, the associated scripts, the output created from the scripts,\n')
        f.write('# and its documentation for any purpose is hereby granted without fee, provided that the\n')
        f.write('# above copyright notice appears in all copies and that both that copyright notice and this\n')
        f.write('# permission notice appear in supporting documentation. Kevin Atkinson makes no\n')
        f.write('# representations about the suitability of this array for any purpose. It is provided\n')
        f.write('# "as is" without express or implied warranty. Generated by scripts/build_parser_lexicons.py\n')
        for w in sorted(words):
            f.write(w + '\n')
    return len(words)

if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    print('given names:', build_given_names())
    print('english words:', build_english_words(sys.argv[1]))
